            '\n',
            'print("Starting FastAPI Backend...")\n',
            'backend_process = subprocess.Popen(["uvicorn", "main:app", "--host", "0.0.0.0", "--port", "8000"], cwd="backend", stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)\n',
            'threading.Thread(target=stream_logs, args=(backend_process, "BACKEND"), daemon=True).start()\n',
