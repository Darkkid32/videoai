            '        line = proc.stdout.readline()\n',
            '        match = re.search(r"(https://[^\s]+)", line)\n',
            '        if match:\n',
            '            url = match.group(1)\n',
            '            break\n',
            '    return proc, url\n',
            '\n',
            'def stream_logs(process, prefix):\n',
            '    for line in iter(process.stdout.readline, ""):\n',
            '        if line:\n',
            '            print(f"[{prefix}] {line.strip()}")\n',
            '            sys.stdout.flush()\n',
            '\n',
            '# Expose API via Localtunnel\n',
            'api_proc, api_url = start_localtunnel(8000)\n',
