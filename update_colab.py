            'threading.Thread(target=stream_logs, args=(worker_process, "WORKER"), daemon=True).start()\n',
            '\n',
            'print("Starting NextJS Frontend...")\n',
            'frontend_process = subprocess.Popen(["npm", "run", "dev"], cwd="frontend", stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)\n',
