            'os.environ["CELERY_BROKER_URL"] = "redis://localhost:6379/0"\n',
            'os.environ["CELERY_RESULT_BACKEND"] = "redis://localhost:6379/1"\n',
            'os.environ["NEXT_PUBLIC_API_URL"] = api_url\n',
            'os.environ["PYTHONPATH"] = "/content/videoai/backend"\n',
